const addFile = (filename, link) => {
  console.log("Adding file", filename, link);
  files.value.unshift({
    name: filename,
    uploadedBy: useUserStore().fullName,
    uploadedByUID: useUserStore().uid,
    lastModified: new Date().toISOString(),
    downloadURL: link,
  });
};

defineExpose({
  addFile,
});

const files = ref([]);

onMounted(async () => {
  files.value = await listEventFiles();
});

const filteredFiles = computed(() => {
  return files.value.filter((file) => {
    return (
      (!props.onlyMyFiles || file.uploadedByUID === useUserStore().uid) &&
      (!props.filter ||
        file.name.toLowerCase().includes(props.filter.toLowerCase()) ||
        file.uploadedBy.toLowerCase().includes(props.filter.toLowerCase()))
    );
  });
});

const removeFile = (file) => {
  deleteEventFile(file.name).then(() => {
    files.value = files.value.filter((f) => f.name !== file.name);
  });
};
</script>

