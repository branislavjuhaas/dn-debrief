as permissive
for select
to authenticated
using (((EXISTS ( SELECT 1
   FROM (((team_scores ts
     JOIN debates d ON ((d.id = ts.debate_id)))
     JOIN rounds r ON ((r.id = d.round_id)))
     JOIN events e ON ((e.id = r.event_id)))
  WHERE ((ts.id = supplementary_speeches.team_score_id) AND (e.status = 'completed'::event_status)))) OR authorize('results.read'::app_permission)));


create policy "Allow users to manage their own supplementary speeches"
on "public"."supplementary_speeches"
as permissive
for all
to authenticated
using ((((( SELECT (auth.jwt() ->> 'user_id'::text)))::bigint = ( SELECT team_scores.adjudicator_id
   FROM team_scores
  WHERE (team_scores.id = supplementary_speeches.team_score_id))) OR authorize('results.write'::app_permission)));


create policy "Allow read access to team assignments"
on "public"."team_assignments"
as permissive
for select
to authenticated
using (((EXISTS ( SELECT 1
   FROM debates
  WHERE ((debates.id = team_assignments.debate_id) AND (debates.round_id IN ( SELECT rounds.id
           FROM rounds
          WHERE (rounds.status <> 'scheduled'::round_status)))))) OR authorize('results.read'::app_permission)));


create policy "Allow users with results.write to manage team assignments"
on "public"."team_assignments"
as permissive
for all
to authenticated
using (authorize('results.write'::app_permission));


