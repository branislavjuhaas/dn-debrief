create policy "Allow update access to user data"
on "public"."users"
as permissive
for update
to authenticated
using (((((( SELECT (auth.jwt() ->> 'user_id'::text)))::bigint = id) AND (( SELECT auth.uid() AS uid) = auth_id)) OR authorize('users.write'::app_permission)));


