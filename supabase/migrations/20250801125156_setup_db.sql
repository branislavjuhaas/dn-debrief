CREATE OR REPLACE FUNCTION public.create_search(text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO ''
AS $function$
  select regexp_replace(extensions.unaccent($1), '[^a-zA-Z0-9]', '', 'g');
$function$
;

