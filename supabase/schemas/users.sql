-- Grants and Revokes
-- Grants usage of the public schema to the Supabase auth admin role.
grant usage on schema public to supabase_auth_admin;

-- Grants execute permission on the custom JWT hook function to the Supabase auth admin.
grant execute
  on function public.custom_access_token_hook
  to supabase_auth_admin;

-- Revokes execute permission on the custom JWT hook function from general roles to restrict its direct invocation.
revoke execute
  on function public.custom_access_token_hook
  from authenticated, anon, public;

-- Grants all permissions on the 'role_permissions' table to the Supabase auth admin.
grant all
  on table public.role_permissions
to supabase_auth_admin;

-- Revokes all permissions on the 'role_permissions' table from general roles.
revoke all
  on table public.role_permissions
  from authenticated, anon, public;