-- Trigger function to automatically create related records in 'claims' and 'details' when a new user is created.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.claims (user_id, role, credential)
  values (new.id, 'user', 0);
  insert into public.details (user_id)
  values (new.id);
  return new;
end;
$$;

create function public.custom_access_token_hook(event jsonb)
returns jsonb
language plpgsql
stable security definer set search_path = ''
as $$
declare
  claims jsonb;
  user_role public.app_role;
  user_credential smallint;
  user_additional jsonb;
  db_user_id bigint;
begin
  -- Initialize claims to the existing claims object from the event
  claims := event->'claims';

  -- Fetch the user's role, credentials, additional data, and db user id
  select c.role, c.credential, c.additional, u.id
    into user_role, user_credential, user_additional, db_user_id
    from public.claims as c
    join public.users as u on c.user_id = u.id
    where u.auth_id = (event->>'user_id')::uuid;

  -- Check if user data was found
  if db_user_id is null then
    raise notice 'User not found for auth_id: %', event->>'user_id';
    -- Return the original event instead of an error
    return event;
  end if;

  -- Append the user-specific claims to the existing claims object
  claims := jsonb_set(claims, '{user_role}', to_jsonb(user_role));
  claims := jsonb_set(claims, '{user_credential}', to_jsonb(coalesce(user_credential, null)));
  claims := jsonb_set(claims, '{user_additional}', coalesce(user_additional, '{}'::jsonb));
  claims := jsonb_set(claims, '{user_id}', to_jsonb(db_user_id));

  -- Update the 'claims' object in the original event
  event := jsonb_set(event, '{claims}', claims);

  return event;
end;
$$;

-- Trigger that executes 'handle_new_user' after a new row is inserted into 'public.users'.
create trigger on_user_created
  after insert on public.users
  for each row execute procedure public.handle_new_user();

-- Defines the central authorization function used by RLS policies.
create function public.authorize(
  requested_permission public.app_permission
)
returns boolean as $$
declare
  bind_permissions int;
  current_user_role public.app_role;
begin
  -- Retrieves the 'user_role' claim from the current user's JWT.
  -- This will be NULL if the claim is not set or is JSON null.
  select ((select auth.jwt()) ->> 'user_role')::public.app_role into current_user_role;

  -- If current_user_role is NULL (e.g., claim missing, or was explicitly set to null),
  -- then the user has no specific role for permission checking.
  if current_user_role is null then
    return false;
  end if;

  -- Checks if the user's role has the requested permission in the 'role_permissions' table.
  select count(*)
  into bind_permissions
  from public.role_permissions
  where public.role_permissions.permission = requested_permission
    and public.role_permissions.role = current_user_role;
  return bind_permissions > 0;
end;
$$ language plpgsql stable security definer set search_path = '';

-- Policies for "users" table
create policy "Allow users to create their own data" on public.users as permissive for insert to authenticated with check ((select auth.uid()) = auth_id);
create policy "Allow users to update their own data" on public.users as permissive for update to authenticated using (((select auth.jwt()->>'user_id')::bigint) = id) with check ((select auth.uid()) = auth_id);
-- Allows all authenticated users to read user data
create policy "Allow authenticated users to read user data" on public.users as permissive for select to authenticated using (true);
-- Allows users with specific roles to read or update user data based on 'users.write' permissions. Deletion is not directly allowed by these policies.
create policy "Allow user roles to update user data" on public.users as permissive for update to authenticated using (authorize('users.write'));

alter table public.users enable row level security;

-- Allows all authenticated users to read a user's awards
create policy "Allow authenticated users to read user awards" on public.awards as permissive for select to authenticated using (true);
-- Policies for role-based access to awards.
-- Allows users with the 'awards.write' permission to create awards.
create policy "Allow user roles to create awards" on public.awards as permissive for insert to authenticated with check (authorize('awards.write'));
-- Allows users with the 'awards.write' permission to delete awards.
create policy "Allow user roles to delete awards" on public.awards as permissive for delete to authenticated using (authorize('awards.write'));

alter table public.awards enable row level security;

-- Policies for "claims" table
