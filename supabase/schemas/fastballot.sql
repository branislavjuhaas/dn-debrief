-- POLICIES FOR THE "motions" TABLE

-- Allows authenticated users to read motions if the motion is prepared, or the round where the motion is used is not a scheduled round or the user has 'motions.read' permission.
create policy "Allow read access to motions" on "motions" for select to authenticated using (
    (
        motion_type = ' prepared'
        or exists (
            select 1
            from "rounds"
            where "rounds"."motion_id" = "motions"."id"
                and "rounds"."status" != 'scheduled'
        )
    )
    or authorize('motions.read')
);
-- Allows users with 'motions.write' permission to create new motions.
create policy "Allow users with motions.write to create motions" on "motions" for insert to authenticated with check (authorize('motions.write'));
-- Allows users with 'motions.write' permission to update existing motions.
create policy "Allow users with motions.write to update motions" on "motions" for update to authenticated using (authorize('motions.write'));

alter table public.motions enable row level security;





-- POLICIES FOR THE "rounds" TABLE

-- Allows authenticated users to read rounds if the round is not scheduled, or the user has 'events.read' permission.
create policy "Allow read access to rounds" on "rounds" for select to authenticated using (
    (status != 'scheduled' or authorize('events.read'))
    or authorize('events.read')
);
-- Allows users with 'events.write' permission to create new rounds.
create policy "Allow users with events.write to create rounds" on "rounds" for insert to authenticated with check (authorize('events.write'));
-- Allows users with 'events.write' permission to update existing rounds.
create policy "Allow users with events.write to update rounds" on "rounds" for update to authenticated using (authorize('events.write'));

alter table public.rounds enable row level security;





