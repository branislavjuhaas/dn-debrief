-- TABLE FOR STORING TEAM SCORES

create table "team_scores" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "team_id" bigint not null references "teams" ("id") on delete cascade,
    "debate_id" bigint not null references "debates" ("id") on delete cascade,
    "adjudicator_id" bigint not null references "users" ("id") on delete cascade default (current_setting('jwt.claims.user_id')::bigint),
