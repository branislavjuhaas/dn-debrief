create type public.round_type as enum (
  'preliminary',
  'elimination'
);





-- ENUMERATION FOR ROUND STATUSES

create type public.round_status as enum (
    'scheduled',
    'in_progress',
    'completed'
);





-- ENUMERATION FOR MOTION TYPES

create type public.motion_type as enum (
    'prepared',
    'impromptu'
);





-- ENUMERATION FOR TEAM TYPES

create type public.team_type as enum (
    'active',
    'archived'
);





-- ENUMERATION FOR ADJUDICATOR ROLES

create type public.adjudicator_role as enum (
    'adjudicator',
    'trainee',
    'chair'
);





-- ENUMERATION FOR SUPPLEMENT TYPES

create type public.supplement_type as enum (
    'cross',
    'reply'
);





-- TABLE FOR STORING MOTIONS

create table "motions" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "motion_type" public.motion_type not null default 'prepared'::public.motion_type,
    "motion_text" text not null,
    "event_id" bigint not null references "events" ("id") on delete cascade,
    "infoslide" text default null
);

comment on table "motions" is 'Stores information about debate motions.';





-- TABLE FOR STORING ROUNDS

create table "rounds" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "event_id" bigint not null references "events" ("id") on delete cascade,
    "motion_id" bigint references "motions" ("id") on delete set null,
    "name" text not null,
    "type" public.round_type not null default 'preliminary'::public.round_type,
    "status" public.round_status not null default 'scheduled'::public.round_status,
    unique ("event_id", "name")
);

comment on table "rounds" is 'Stores information about debate rounds.';
create index ix_rounds_event_id on public.rounds (event_id);
create index ix_rounds_motion_id on public.rounds (motion_id);





-- TABLE FOR STORING DEBATE TEAMS

create table "teams" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "name" text not null unique,
    "type" public.team_type not null default 'active'::public.team_type,
    "search_index" text generated always as (public.create_search(lower(name))) stored
);

comment on table "teams" is 'Stores information about debate teams.';

create index ix_teams_type on public.teams (type);
create index ix_teams_search_index on public.teams (search_index);





-- TABLE FOR STORING TEAM MEMBERSHIPS

create table "team_memberships" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "team_id" bigint not null references "teams" ("id") on delete cascade,
    "user_id" bigint not null references "users" ("id") on delete cascade,
    "event_id" bigint not null references "events" ("id") on delete cascade,
    unique ("team_id", "user_id", "event_id")
);

comment on table "team_memberships" is 'Stores relationships between users and the teams they belong to.';
create index ix_team_memberships_team_id on public.team_memberships (team_id);
create index ix_team_memberships_user_id on public.team_memberships (user_id);
create index ix_team_memberships_event_id on public.team_memberships (event_id);





-- TABLE FOR STORING DEBATES

create table "debates" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "round_id" bigint not null references "rounds" ("id") on delete cascade,
    "room" text not null,
    unique ("round_id", "room")
);

comment on table "debates" is 'Stores information about debates within rounds used for tabbing and adjudication.';
create index ix_debates_round_id on public.debates (round_id);





-- TABLE FOR STORING ADJUDICATOR ASSIGNMENTS

create table "adjudicator_assignments" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "debate_id" bigint not null references "debates" ("id") on delete cascade,
    "user_id" bigint not null references "users" ("id") on delete cascade,
    "role" public.adjudicator_role not null default 'adjudicator'::public.adjudicator_role,
    unique ("debate_id", "user_id")
);

comment on table "adjudicator_assignments" is 'Stores adjudicator assignments for debates.';
create index ix_adjudicator_assignments_debate_id on public.adjudicator_assignments (debate_id);
create index ix_adjudicator_assignments_user_id on public.adjudicator_assignments (user_id);





-- TABLE FOR STORING TEAM ASSIGNMENTS

create table "team_assignments" (
    "id" bigint generated by default as identity primary key,
    "created_at" timestamptz not null default now(),
    "debate_id" bigint not null references "debates" ("id") on delete cascade,
    "team_id" bigint not null references "teams" ("id") on delete cascade,
