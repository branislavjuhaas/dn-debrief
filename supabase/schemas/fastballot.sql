-- POLICIES FOR THE "team_scores" TABLE

-- Allows authenticated users to read team scores if the event is completed, or the user has 'results.read' permission.
create policy "Allow read access to team scores" on "team_scores" for select to authenticated using (
    (
        exists (
            select 1
            from "debates" d
            join "rounds" r on r.id = d.round_id
            join "events" e on e.id = r.event_id
            where d.id = "team_scores".debate_id
                and e.status = 'completed'
        )
        or authorize('results.read')
    )
);

-- Allows authenticated users to do anything with the team scores if they are the adjudicator or have 'results.write' permission.
create policy "Allow users to manage their own team scores" on "team_scores" for all to authenticated using (
    ((select (auth.jwt()->>'user_id'))::bigint) = adjudicator_id
    or authorize('results.write')
);

alter table public.team_scores enable row level security;





